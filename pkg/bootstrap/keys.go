// Generated private keys (for example the ArgoCD GitHub deploy key written by the
// template's kubernetes/init.sh) live outside the terraform, kubernetes and gitops
// directories, because `blcli apply init-repos` turns each of those into a git
// repository and commits everything in it.

const (
	// KeysDirEnv names the directory for generated private keys. blcli passes it to
	// kubernetes/init.sh and to component install scripts. Set it in the environment
	// to choose another location.
	KeysDirEnv = "BLCLI_KEYS_DIR"
	// DefaultKeysDirName is the keys directory created in the workspace root, next to
	// (not inside) the terraform, kubernetes and gitops directories.
	DefaultKeysDirName = ".blcli-keys"
	// legacyKeysDirName is where blcli used to put keys: <workspace>/kubernetes/keys.
	legacyKeysDirName = "keys"
	// argocdKeysDirEnv is the override the template's ArgoCD install script reads
	// (it defaults to ../../keys, the legacy location).
	argocdKeysDirEnv = "ARGOCD_KEYS_DIR"

	kubernetesGitignoreEntry = "keys/"
)

// KeysDirForWorkspace returns the directory for generated private keys:
// $BLCLI_KEYS_DIR when set, otherwise <workspace>/.blcli-keys.
func KeysDirForWorkspace(workspace string) (string, error) {
	if dir := strings.TrimSpace(os.Getenv(KeysDirEnv)); dir != "" {
		return filepath.Abs(dir)
	}
	absWorkspace, err := filepath.Abs(workspace)
	if err != nil {
		return "", fmt.Errorf("resolve workspace: %w", err)
	}
	return filepath.Join(absWorkspace, DefaultKeysDirName), nil
}

// ensureKeysDir creates dir with mode 0700 (and tightens it if it already exists) and
// writes a .gitignore that ignores everything in it, so nothing there is committed even
// if the workspace itself sits inside a git repository.
func ensureKeysDir(dir string) error {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return fmt.Errorf("create keys dir %s: %w", dir, err)
	}
	if err := os.Chmod(dir, 0o700); err != nil {
		return fmt.Errorf("chmod keys dir %s: %w", dir, err)
	}
	gitignore := filepath.Join(dir, ".gitignore")
	if _, err := os.Stat(gitignore); os.IsNotExist(err) {
		if err := os.WriteFile(gitignore, []byte("# Private keys generated by blcli. Never commit them.\n*\n"), 0o600); err != nil {
			return fmt.Errorf("write %s: %w", gitignore, err)
		}
	}
	return nil
}

// hasKeyFiles reports whether dir contains a file other than .gitignore.
func hasKeyFiles(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		if e.Name() != ".gitignore" {
			return true
		}
	}
	return false
}

// migrateLegacyKeysDir moves keys that an older blcli generated in
// <kubernetes>/keys to keysDir, so that the deploy key already registered on GitHub
// keeps working and the private key leaves the kubernetes repository. It does nothing
// when there is no legacy key, or when keysDir already holds keys (then the legacy
// directory is left for the user, and `apply init-repos` refuses to commit it).
func migrateLegacyKeysDir(kubernetesDir, keysDir string, out io.Writer) error {
	absKubernetesDir, err := filepath.Abs(kubernetesDir)
	if err != nil {
		return fmt.Errorf("resolve kubernetes dir: %w", err)
	}
	legacy := filepath.Join(absKubernetesDir, legacyKeysDirName)
	if filepath.Clean(legacy) == filepath.Clean(keysDir) || !hasKeyFiles(legacy) {
		return nil
	}
	if hasKeyFiles(keysDir) {
		fmt.Fprintf(out, "[WARN] Found key files in %s, inside the kubernetes repository, and keys in %s.\n", legacy, keysDir)
		fmt.Fprintf(out, "[WARN] blcli uses %s. Move or delete %s before committing the kubernetes directory.\n", keysDir, legacy)
		return nil
	}
	if err := ensureKeysDir(keysDir); err != nil {
		return err
	}
	entries, err := os.ReadDir(legacy)
	if err != nil {
		return fmt.Errorf("read %s: %w", legacy, err)
	}
	for _, e := range entries {
		if e.Name() == ".gitignore" {
			continue
		}
		if err := os.Rename(filepath.Join(legacy, e.Name()), filepath.Join(keysDir, e.Name())); err != nil {
			return fmt.Errorf("move %s to %s: %w", filepath.Join(legacy, e.Name()), keysDir, err)
		}
	}
	if !hasKeyFiles(legacy) {
		_ = os.Remove(filepath.Join(legacy, ".gitignore"))
		_ = os.Remove(legacy)
	}
	fmt.Fprintf(out, "[INFO] Moved generated keys from %s to %s, outside the kubernetes repository.\n", legacy, keysDir)
	fmt.Fprintf(out, "[WARN] If %s was ever committed or pushed, treat those keys as leaked: generate a new deploy key, replace it on GitHub and re-seal it.\n", legacy)
	return nil
}

// resolveApplyKeysDir returns the keys directory for `apply kubernetes`: the workspace
// keys directory, or the legacy <kubernetes>/keys when only that one holds keys (a
// workspace generated by an older blcli and not re-initialized).
func resolveApplyKeysDir(kubernetesDir string, out io.Writer) (string, error) {
	absKubernetesDir, err := filepath.Abs(kubernetesDir)
	if err != nil {
		return "", err
	}
	keysDir, err := KeysDirForWorkspace(filepath.Dir(absKubernetesDir))
	if err != nil {
		return "", err
	}
	legacy := filepath.Join(absKubernetesDir, legacyKeysDirName)
	if !hasKeyFiles(keysDir) && hasKeyFiles(legacy) {
		fmt.Fprintf(out, "[WARN] Using keys in %s, inside the kubernetes repository. Run blcli init again or move them to %s so that they are never committed.\n", legacy, keysDir)
		return legacy, nil
	}
	return keysDir, nil
}

// keysDirEnv returns the environment entries that point scripts at keysDir.
// ARGOCD_KEYS_DIR is only added when the caller has not set it.
func keysDirEnv(keysDir string) []string {
	env := []string{fmt.Sprintf("%s=%s", KeysDirEnv, keysDir)}
	if _, ok := os.LookupEnv(argocdKeysDirEnv); !ok {
		env = append(env, fmt.Sprintf("%s=%s", argocdKeysDirEnv, keysDir))
	}
	return env
}

// ensureGitignoreEntry appends entry to dir/.gitignore unless a line already equals it.
func ensureGitignoreEntry(dir, entry string) error {
	path := filepath.Join(dir, ".gitignore")
	content, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read %s: %w", path, err)
	}
	scanner := bufio.NewScanner(bytes.NewReader(content))
	for scanner.Scan() {
		if strings.TrimSpace(scanner.Text()) == entry {
			return nil
		}
	}
	var b strings.Builder
	b.Write(content)
	if len(content) > 0 && !bytes.HasSuffix(content, []byte("\n")) {
		b.WriteString("\n")
	}
	if len(content) == 0 {
		b.WriteString("# Added by blcli: private keys must never be committed.\n")
	}
	b.WriteString(entry + "\n")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

// privateKeyPEM matches PEM and OpenSSH private keys, e.g. "-----BEGIN OPENSSH PRIVATE KEY-----",
// "-----BEGIN RSA PRIVATE KEY-----", "-----BEGIN ENCRYPTED PRIVATE KEY-----" and
// "-----BEGIN PGP PRIVATE KEY BLOCK-----".
var privateKeyPEM = regexp.MustCompile(`-----BEGIN [A-Z0-9 ]*PRIVATE KEY( BLOCK)?-----`)

// maxKeyScanBytes limits how much of each file is searched for a private key.
const maxKeyScanBytes = 1 << 20

var privateKeyFileSuffixes = []string{".pem", ".key", ".p12", ".pfx"}

// KeyMaterialFinding is one file or directory that looks like private-key material.
type KeyMaterialFinding struct {
	Path   string // relative to the scanned directory
	Reason string
}

// findPrivateKeyMaterial walks dir (skipping .git) and returns files that hold or look
// like private keys: content with a PEM/OpenSSH private key header, file names id_*
// (except *.pub), *.pem, *.key, *.p12, *.pfx, and keys/ directories that hold anything
// other than public keys.
func findPrivateKeyMaterial(dir string) ([]KeyMaterialFinding, error) {
	var findings []KeyMaterialFinding
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, relErr := filepath.Rel(dir, path)
		if relErr != nil {
			rel = path
		}
		name := d.Name()
		if d.IsDir() {
			if name == ".git" && path != dir {
				return filepath.SkipDir
			}
			if name == legacyKeysDirName && path != dir && dirHoldsPrivateFiles(path) {
				findings = append(findings, KeyMaterialFinding{Path: rel + string(filepath.Separator), Reason: "key directory"})
			}
			return nil
		}
		lower := strings.ToLower(name)
		if strings.HasPrefix(lower, "id_") && !strings.HasSuffix(lower, ".pub") {
			findings = append(findings, KeyMaterialFinding{Path: rel, Reason: "SSH private key file name"})
			return nil
		}
		for _, suffix := range privateKeyFileSuffixes {
			if strings.HasSuffix(lower, suffix) {
				findings = append(findings, KeyMaterialFinding{Path: rel, Reason: "key file extension " + suffix})
				return nil
			}
		}
		if !d.Type().IsRegular() {
			return nil
		}
		if found, err := fileHasPrivateKey(path); err != nil {
			return err
		} else if found {
			findings = append(findings, KeyMaterialFinding{Path: rel, Reason: "contains a private key"})
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Slice(findings, func(i, j int) bool { return findings[i].Path < findings[j].Path })
	return findings, nil
}

// dirHoldsPrivateFiles reports whether a keys/ directory holds a file that is neither
// .gitignore nor a public key.
func dirHoldsPrivateFiles(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		if e.IsDir() || e.Name() == ".gitignore" || strings.HasSuffix(e.Name(), ".pub") {
			continue
		}
		return true
	}
	return false
}

func fileHasPrivateKey(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	buf, err := io.ReadAll(io.LimitReader(f, maxKeyScanBytes))
	if err != nil {
		return false, err
	}
	return privateKeyPEM.Match(buf), nil
}

// KeyMaterialError is returned when a directory that would be committed holds private keys.
type KeyMaterialError struct {
	Dir      string
	Findings []KeyMaterialFinding
	KeysDir  string
}

func (e *KeyMaterialError) Error() string {
	var b strings.Builder
	fmt.Fprintf(&b, "refusing to commit %s: it contains private-key material:\n", e.Dir)
	for _, f := range e.Findings {
		fmt.Fprintf(&b, "  - %s (%s)\n", f.Path, f.Reason)
	}
	fmt.Fprintf(&b, "Move these files out of %s", e.Dir)
	if e.KeysDir != "" {
		fmt.Fprintf(&b, " (blcli keeps generated keys in %s)", e.KeysDir)
	}
	b.WriteString(", then run the command again. A .gitignore entry is not enough: the files must not be in the repository directory.\n")
	b.WriteString("If any of them was ever committed or pushed, treat it as leaked and rotate it; removing it from the latest commit does not remove it from history.")
	return b.String()
}
