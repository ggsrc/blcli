func TestKeysDirForWorkspace(t *testing.T) {
	t.Setenv(KeysDirEnv, "")
	root := t.TempDir()
	got, err := KeysDirForWorkspace(root)
	if err != nil {
		t.Fatal(err)
	}
	if want := filepath.Join(root, "keys"); got != want {
		t.Errorf("KeysDirForWorkspace() = %q, want %q", got, want)
	}

	override := filepath.Join(root, "elsewhere")
	t.Setenv(KeysDirEnv, override)
	got, err = KeysDirForWorkspace(root)
	if err != nil {
		t.Fatal(err)
	}
	if got != override {
		t.Errorf("KeysDirForWorkspace() with %s = %q, want %q", KeysDirEnv, got, override)
	}
}

func TestResolveApplyKeysDir(t *testing.T) {
	t.Setenv(KeysDirEnv, "")
	root := t.TempDir()
	k8sDir := filepath.Join(root, "kubernetes")
	if err := os.MkdirAll(k8sDir, 0o755); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer

	got, err := resolveApplyKeysDir(k8sDir, &out)
	if err != nil {
		t.Fatal(err)
	}
	if want := filepath.Join(root, "keys"); got != want {
		t.Errorf("resolveApplyKeysDir() = %q, want %q", got, want)
	}

	// A workspace generated by an older blcli still finds its key, with a warning.
	writeTestFile(t, filepath.Join(k8sDir, "keys", "argocd_github"), testPrivateKey)
	got, err = resolveApplyKeysDir(k8sDir, &out)
	if err != nil {
		t.Fatal(err)
	}
	if want := filepath.Join(k8sDir, "keys"); got != want {
		t.Errorf("resolveApplyKeysDir() with legacy keys = %q, want %q", got, want)
	}
	if !strings.Contains(out.String(), "inside the kubernetes repository") {
		t.Errorf("expected a warning, got %q", out.String())
	}

	// Once the workspace keys dir holds keys, it wins.
	writeTestFile(t, filepath.Join(root, "keys", "argocd_github"), testPrivateKey)
	got, err = resolveApplyKeysDir(k8sDir, &out)
	if err != nil {
		t.Fatal(err)
	}
	if want := filepath.Join(root, "keys"); got != want {
		t.Errorf("resolveApplyKeysDir() = %q, want %q", got, want)
	}
}

func TestMigrateLegacyKeysDirKeepsBothWhenNewDirHasKeys(t *testing.T) {
	root := t.TempDir()
	k8sDir := filepath.Join(root, "kubernetes")
	keysDir := filepath.Join(root, "keys")
	writeTestFile(t, filepath.Join(k8sDir, "keys", "argocd_github"), "old")
	writeTestFile(t, filepath.Join(keysDir, "argocd_github"), "new")

	var out bytes.Buffer
	if err := migrateLegacyKeysDir(k8sDir, keysDir, &out); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(filepath.Join(keysDir, "argocd_github")); string(b) != "new" {
		t.Errorf("existing key overwritten: %q", b)
	}
	if b, _ := os.ReadFile(filepath.Join(k8sDir, "keys", "argocd_github")); string(b) != "old" {
		t.Errorf("legacy key changed: %q", b)
	}
	if !strings.Contains(out.String(), "[WARN]") {
		t.Errorf("expected a warning, got %q", out.String())
	}
}

func TestApplyCustomInstallGetsKeysDir(t *testing.T) {
	componentDir := t.TempDir()
	keysDir := filepath.Join(t.TempDir(), "keys")

	var env []string
	withFakeExternalExecutor(t, func(ctx context.Context, spec ExternalCommandSpec, mode externalCommandOutputMode) (ExternalCommandResult, error) {
		env = spec.Env
		return fakeExternalResult(spec, ""), nil
	})

	component := template.KubernetesComponent{Name: "argocd", Install: "bash ./install"}

	t.Setenv(argocdKeysDirEnv, "")
	os.Unsetenv(argocdKeysDirEnv)
	if err := applyWithCustomWithProgress(context.Background(), ApplyKubernetesOptions{KeysDir: keysDir}, component, componentDir, progressStepLogger{}); err != nil {
		t.Fatalf("applyWithCustomWithProgress() error = %v", err)
	}
	for _, want := range []string{KeysDirEnv + "=" + keysDir, argocdKeysDirEnv + "=" + keysDir} {
		if !containsString(env, want) {
			t.Errorf("install env does not contain %q", want)
		}
	}

	// A caller-provided ARGOCD_KEYS_DIR is left alone.
	t.Setenv(argocdKeysDirEnv, "/custom/keys")
	if err := applyWithCustomWithProgress(context.Background(), ApplyKubernetesOptions{KeysDir: keysDir}, component, componentDir, progressStepLogger{}); err != nil {
		t.Fatalf("applyWithCustomWithProgress() error = %v", err)
	}
	if containsString(env, argocdKeysDirEnv+"="+keysDir) {
		t.Errorf("install env overrides the caller's %s", argocdKeysDirEnv)
	}
}

